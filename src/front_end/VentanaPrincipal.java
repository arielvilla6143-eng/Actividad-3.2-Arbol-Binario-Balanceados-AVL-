    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
         try {
            if (txtId.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty() ||
                txtPuesto.getText().trim().isEmpty() || txtDepartamento.getText().trim().isEmpty() ||
                txtSalario.getText().trim().isEmpty()) {
                txtAreaResultados.setText("Error: Todos los campos de texto son obligatorios para agregar.\n");
                return;
            }

            Integer id = Integer.parseInt(txtId.getText().trim());
            String nombre = txtNombre.getText().trim();
            String puesto = txtPuesto.getText().trim();
            String depto = txtDepartamento.getText().trim();
            Double salario = Double.parseDouble(txtSalario.getText().trim());

            Empleado nuevo = new Empleado(id, nombre, puesto, depto, salario);
            arbol.insertar(nuevo);
            txtAreaResultados.setText("Empleado agregado exitosamente:\n" + nuevo.toString() + "\n");
            limpiarCampos();
        } catch (NumberFormatException e) {
            txtAreaResultados.setText("Error: El ID debe ser un entero y el Salario un número válido.\n");
        } catch (IllegalArgumentException e) {
            txtAreaResultados.setText("Error de validación: " + e.getMessage() + "\n");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        try {
            if (txtId.getText().trim().isEmpty()) {
                txtAreaResultados.setText("Ingrese un ID en el campo 'ID' para buscar.\n");
                return;
            }
            Integer id = Integer.parseInt(txtId.getText().trim());
            Empleado emp = arbol.buscar(id);
            if (emp != null) {
                txtAreaResultados.setText("Empleado Encontrado:\n" + emp.toString() + "\n");
            } else {
                txtAreaResultados.setText("No se encontró ningún empleado con el ID: " + id + "\n");
            }
        } catch (NumberFormatException e) {
            txtAreaResultados.setText("Error: Ingrese un ID numérico válido para buscar.\n");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
    try {
        if (txtId.getText().trim().isEmpty()) {
            txtAreaResultados.setText("Ingrese un ID en el campo 'ID' para eliminar.\n");
            return;
        }
        Integer id = Integer.parseInt(txtId.getText().trim());
        
        arbol.eliminar(id); // Se llama directamente, sin boolean
        txtAreaResultados.setText("Comando de eliminación ejecutado para el ID " + id + ".\n");
        limpiarCampos();
        
    } catch (NumberFormatException e) {
        txtAreaResultados.setText("Error: Ingrese un ID numérico válido para eliminar.\n");
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

